// The page in English, Japanese and Simplified Chinese (ADR 0015). The
// server speaks English, which the log and the checks read; the page
// translates what it sends: feed lines by key, refusals by their English
// text, lessons by id, famous days by date, bots by id. Terms follow what
// Japanese and mainland Chinese retail traders and brokers actually say.
// Shared by the market page and test/i18n.test.ts.

import { CLUES, EVENTS, LESSONS, LINES, NEWS, SCENARIOS } from "./i18n-long.js";

export const LANGS = ["en", "ja", "zh"];

// Yen as ¥ in every language, Peter's choice (ADR 0078), so an amount reads the same on every page and is short
// beside the figures. Japanese brokers write 円 and a mainland reader may take a bare ¥ for the yuan; the account is
// always in yen, which the About page says, so ¥ here is the yen.
export function money(lang, n) {
  const sign = n < 0 ? "−" : "";
  return `${sign}¥${Math.abs(Math.round(n)).toLocaleString("en-AU")}`;
}

// Fills {name} slots. A slot holding money is formatted for the language.
function fill(lang, text, args, nameOf) {
  return text.replace(/\{(\w+\+?)\}/g, (_, k) => {
    if (k === "who") return nameOf(args.who);
    if (k === "pnl" || k === "amount" || k === "debt") return money(lang, args[k]);
    if (k === "feat") return (T[lang].ui.feats[args.feat] ?? T.en.ui.feats[args.feat] ?? [args.feat])[0];
    if (k === "pnl+") return (args.pnl >= 0 ? "+" : "") + money(lang, args.pnl);
    return String(args[k] ?? "");
  });
}

// A feed line in the reader's language, or its English if a key is new.
export function news(lang, line, nameOf) {
  // A Simulation's headline is the situation's own words (ADR 0027).
  if (line.key === "headline") return T[lang].scenarios[line.args.scenario]?.headlines[line.args.n] ?? line.text;
  if (line.key === "story") return T[lang].stories[line.args.n] ?? line.text;
  if (line.key === "clue") return clueText(lang, line.args.clue, line.args.n) ?? line.text;
  const text = T[lang].news[line.key];
  return text ? fill(lang, text, line.args, nameOf) : line.text;
}

// A refusal or hint from the server, by its English text. The one hint
// with a number in it is matched by its pattern.
export function refusal(lang, english) {
  if (T[lang].refusals[english]) return T[lang].refusals[english];
  const m = english.match(/^This lesson wants a (Buy|Sell) at (\d+)×\. Set Leverage to \d+× first\.$/);
  if (m) return T[lang].wants[m[1] === "Buy" ? "buy" : "sell"].replaceAll("{lev}", m[2]);
  const s = english.match(/^This lesson wants a Stop Loss at 1%, not ([\d.]+)%\. Drag the thumb as close to the middle line as it goes\.$/);
  if (s) return T[lang].wants.stop.replaceAll("{pct}", s[1]);
  return english;
}

