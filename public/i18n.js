export const LANGS = ["en", "ja", "zh"];

// Yen in each language: Japanese brokers write 1,000,000円; mainland
// readers would take a bare ¥ for renminbi, so Chinese says 日元.
export function money(lang, n) {
  const sign = n < 0 ? "−" : "";
  const amount = Math.abs(Math.round(n)).toLocaleString("en-AU");
  if (lang === "ja") return `${sign}${amount}円`;
  if (lang === "zh") return `${sign}${amount} 日元`;
  return `${sign}¥${amount}`;
}

// Fills {name} slots. A slot holding money is formatted for the language.
function fill(lang, text, args, nameOf) {
  return text.replace(/\{(\w+)\}/g, (_, k) => {
    if (k === "who") return nameOf(args.who);
    if (k === "pnl" || k === "amount") return money(lang, args[k]);
    if (k === "pnl+") return (args.pnl >= 0 ? "+" : "") + money(lang, args.pnl);
    return String(args[k] ?? "");
  });
}

// A feed line in the reader's language, or its English if a key is new.
export function news(lang, line, nameOf) {
  const text = T[lang].news[line.key];
  return text ? fill(lang, text, line.args, nameOf) : line.text;
}

// A refusal or hint from the server, by its English text. The one hint
// with a number in it is matched by its pattern.
export function refusal(lang, english) {
  if (T[lang].refusals[english]) return T[lang].refusals[english];
  const m = english.match(/^This lesson wants a (Buy|Sell) at (\d+)×\. Set Leverage to \d+× first\.$/);
  if (m) return T[lang].wants[m[1] === "Buy" ? "buy" : "sell"].replaceAll("{lev}", m[2]);
  return english;
}

